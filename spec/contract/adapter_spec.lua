-- The fake adapter must honour contracts/wow-adapter.md, otherwise Core tests prove nothing.
local FakeWow = require("fake_wow")

describe("fake WoW adapter contract", function()
	local fake, api
	before_each(function()
		fake = FakeWow.new({ bindings = { ["1"] = "ACTIONBUTTON1", ["SHIFT-1"] = "ACTIONBUTTON1" } })
		api = fake.api
	end)

	it("reads bindings by key and by command", function()
		assert.equal("ACTIONBUTTON1", api.getBindingAction("1"))
		assert.is_nil(api.getBindingAction("2"))
		assert.same({ "1", "SHIFT-1" }, api.getBindingKeys("ACTIONBUTTON1"))
	end)

	it("lists commands with headers", function()
		local rows = api.listBindingCommands()
		assert.is_true(rows[1].header)
		assert.equal("HEADER_MOVEMENT", rows[1].command)
	end)

	it("sets and clears bindings", function()
		assert.is_true(api.setBinding("2", "JUMP"))
		assert.equal("JUMP", api.getBindingAction("2"))
		assert.is_true(api.setBinding("2", nil))
		assert.is_nil(api.getBindingAction("2"))
	end)

	it("rejects unknown named commands but accepts typed ones", function()
		assert.is_false(api.setBinding("3", "NOSUCHCOMMAND"))
		assert.is_true(api.setBinding("3", "SPELL Anything"))
		assert.is_true(api.setBinding("4", "CLICK Missing:LeftButton"))
	end)

	it("saving to the account set deletes the character set", function()
		api.saveBindings("character")
		assert.equal("character", api.currentBindingSet())
		assert.is_not_nil(fake.state.sets.character)
		api.saveBindings("account")
		assert.is_nil(fake.state.sets.character)
		assert.equal("account", api.currentBindingSet())
	end)

	it("throws on protected calls in combat", function()
		fake.setCombat(true)
		assert.is_true(api.inCombat())
		assert.has_error(function() api.setBinding("1", nil) end)
		assert.has_error(function() api.saveBindings("character") end)
		assert.has_error(function() api.setAddonEnabled("Bartender4", true) end)
		assert.has_error(function() api.reloadUI() end)
		assert.has_error(function() api.bt4SetProfile("Raid") end)
	end)

	it("reports addon state and switches Bartender4 profiles", function()
		assert.is_true(api.isAddonInstalled("Bartender4"))
		assert.is_false(api.isAddonLoaded("Bartender4"))
		assert.is_nil(api.bt4Profiles())
		assert.is_true(api.setAddonEnabled("Bartender4", true))
		fake.simulateReload()
		assert.is_true(api.isAddonLoaded("Bartender4"))
		assert.same({ "Default", "Raid" }, api.bt4Profiles())
		assert.is_true(api.bt4SetProfile("Raid"))
		assert.equal("Raid", api.bt4CurrentProfile())
		assert.is_false(api.bt4SetProfile("Missing"))
	end)

	it("records reloads", function()
		api.reloadUI()
		assert.equal(1, fake.state.reloads)
	end)

	it("answers validation queries", function()
		fake = FakeWow.new({ spells = { Frostbolt = true }, macros = { Burst = true }, items = { Hearthstone = 1 } })
		api = fake.api
		assert.is_true(api.knownSpells().Frostbolt)
		assert.is_true(api.macroExists("Burst"))
		assert.is_false(api.macroExists("Nope"))
		assert.equal(1, api.itemCount("Hearthstone"))
		assert.equal(0, api.itemCount("Nope"))
		assert.is_false(api.frameExists("BT4Button1"))
	end)

	it("exposes identity and environment", function()
		assert.equal("Tester - Realm", api.charKey())
		assert.equal(1000, api.now())
		assert.equal("enUS", api.locale())
		assert.equal("Label MOVEMENT", api.headerLabel("MOVEMENT"))
	end)
end)
