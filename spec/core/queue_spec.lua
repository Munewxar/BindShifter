local Env = require("env")

describe("Service: combat queue (US2)", function()
	local env, s
	before_each(function()
		env = Env.new({ bindings = { ["1"] = "ACTIONBUTTON1" } })
		s = env.service
		s:saveCurrent("A")
		env.fake.bind("1", "JUMP")
		s:saveCurrent("B")
	end)

	it("defers an apply until combat ends, without protected calls in combat", function()
		local step = s:requestApply("A")
		env.fake.setCombat(true)
		local before = env.fake.state.protectedCalls
		assert.equal("queued", s:confirmApply(step).step)
		assert.equal(before, env.fake.state.protectedCalls)
		assert.equal("JUMP", env.fake.bindings()["1"])
		assert.is_not_nil(env.noted("msgQueued"))
		assert.equal("apply", env.db.chars["Tester - Realm"].combatQueued.type)

		env.fake.setCombat(false)
		local done = s:onCombatEnd()
		assert.equal("done", done.step)
		assert.equal("ACTIONBUTTON1", env.fake.bindings()["1"])
		assert.is_nil(env.db.chars["Tester - Realm"].combatQueued)
	end)

	it("keeps only the newest request", function()
		env.fake.bind("1", "TARGETSELF")
		local a = s:requestApply("A")
		local b = s:requestApply("B")
		env.fake.setCombat(true)
		s:confirmApply(a)
		s:confirmApply(b)
		assert.is_not_nil(env.noted("msgQueuedReplaced"))
		env.fake.setCombat(false)
		s:onCombatEnd()
		assert.equal("JUMP", env.fake.bindings()["1"])
		assert.is_nil(s:onCombatEnd())
	end)

	it("defers undo in combat", function()
		env.fake.state.active = "character"
		s:confirmApply(s:requestApply("A"))
		env.fake.setCombat(true)
		assert.equal("queued", s:undo().step)
		env.fake.setCombat(false)
		s:onCombatEnd()
		assert.equal("JUMP", env.fake.bindings()["1"])
	end)

	it("reports an operation lost at logout on the next load", function()
		env.fake.setCombat(true)
		s:confirmApply(s:requestApply("A"))
		env.fake.setCombat(false)
		local fresh = env.reload()
		fresh:onLoad()
		assert.is_not_nil(env.noted("msgQueuedCancelled"))
		assert.is_nil(env.db.chars["Tester - Realm"].combatQueued)
	end)
end)
