local Env = require("env")

describe("Service: profiles (US1)", function()
	local env, s
	before_each(function()
		env = Env.new({ bindings = { ["1"] = "ACTIONBUTTON1", ["Q"] = "SPELL Frostbolt" },
			spells = { Frostbolt = true } })
		s = env.service
	end)

	it("saves the current bindings with the current mode", function()
		local step = s:saveCurrent("Raid")
		assert.equal("done", step.step)
		assert.equal(2, step.count)
		local p = s:getProfile("raid")
		assert.equal("blizzard", p.mode)
		assert.same({ ["1"] = "ACTIONBUTTON1", ["Q"] = "SPELL Frostbolt" }, p.bindings)
		assert.equal("raid", env.db.chars["Tester - Realm"].activeProfile)
		assert.is_not_nil(env.noted("msgSaved"))
	end)

	it("asks before overwriting an existing profile", function()
		s:saveCurrent("Raid")
		env.fake.bind("2", "JUMP")
		local step = s:saveCurrent("RAID")
		assert.equal("confirmOverwrite", step.step)
		assert.equal(2, env.ns.Util.count(s:getProfile("Raid").bindings))
		s:saveCurrent("RAID", true)
		assert.equal("JUMP", s:getProfile("Raid").bindings["2"])
	end)

	it("rejects invalid names", function()
		assert.same("errNameEmpty", s:saveCurrent("  ").err)
	end)

	it("previews and applies a profile exactly", function()
		s:saveCurrent("Raid")
		env.fake.bind("1", "JUMP")
		env.fake.bind("2", "ACTIONBUTTON2")
		local step = s:requestApply("raid")
		assert.equal("preview", step.step)
		assert.same({ ["1"] = { from = "JUMP", to = "ACTIONBUTTON1" } }, step.diff.changed)
		assert.same({ ["2"] = "ACTIONBUTTON2" }, step.diff.removed)
		local done = s:confirmApply(step)
		assert.equal("done", done.step)
		assert.equal("apply", done.report.kind)
		assert.same({ ["1"] = "ACTIONBUTTON1", ["Q"] = "SPELL Frostbolt" }, env.fake.bindings())
		assert.equal("raid", env.db.chars["Tester - Realm"].activeProfile)
	end)

	it("reports no changes when bindings already match", function()
		s:saveCurrent("Raid")
		assert.equal("noChanges", s:requestApply("Raid").step)
	end)

	it("applies a profile saved by another character", function()
		s:saveCurrent("Raid")
		env.fake.state.char = "Other - Realm"
		local other = env.reload()
		env.fake.bind("1", nil)
		local step = other:requestApply("Raid")
		other:confirmApply(step)
		assert.equal("ACTIONBUTTON1", env.fake.bindings()["1"])
		assert.equal("raid", env.db.chars["Other - Realm"].activeProfile)
	end)

	it("renames, duplicates and deletes", function()
		s:saveCurrent("Raid")
		assert.equal("done", s:rename("Raid", "Raid ICC").step)
		assert.equal("raid icc", env.db.chars["Tester - Realm"].activeProfile)
		assert.equal("errNameTaken", s:duplicate("Raid ICC", "raid icc").err)
		assert.equal("done", s:duplicate("Raid ICC", "Copy").step)
		assert.equal("done", s:delete("Copy").step)
		local names = {}
		for _, p in ipairs(s:listProfiles()) do
			names[#names + 1] = p.name
		end
		assert.same({ "Raid ICC" }, names)
	end)

	it("lists profiles with counts and the active flag", function()
		s:saveCurrent("Raid")
		local list = s:listProfiles()
		assert.equal(1, #list)
		assert.equal(2, list[1].count)
		assert.is_true(list[1].active)
	end)

	it("includes validation issues in the preview and the report", function()
		env.fake.bind("E", "SPELL Fireball")
		s:saveCurrent("Raid")
		env.fake.bind("E", nil)
		local step = s:requestApply("Raid")
		assert.equal("unknownSpell", step.issues[1].reason)
		local done = s:confirmApply(step)
		assert.equal("unknownSpell", done.report.issues[1].reason)
		assert.equal("SPELL Fireball", env.fake.bindings().E)
	end)
end)
